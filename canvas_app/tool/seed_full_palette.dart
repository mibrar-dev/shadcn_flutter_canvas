/// Drop-path props copy (design_canvas.dart onAccept):
/// `entry == null ? {} : Map.of(entry.defaults)`.
Map<String, dynamic> _dropProps(String kind) {
  final defaults = _catalogDefaults[kind];
  if (defaults == null) return <String, dynamic>{};
  return Map<String, dynamic>.of(defaults);
}

int _uidCounter = 0;

/// Unique node/item id in the store's `u<N>` scheme.
String _nextId() => 'u${++_uidCounter}';

/// Builds the full-palette demo document (screens, nodes, theme, meta).
ScreenDoc buildFullPaletteDoc() {
  _uidCounter = 0;
  final screens = <CanvasScreen>[];
  final nodes = <CanvasNode>[];

  // Screen ids are positional: s1..s8 follow _sectionOrder, s9 is Tier demo.
  String screenIdForSection(int index) => 's${index + 1}';
  const tierScreenId = 's9';
  // Nav pair: Controls button -> Display, Display's first item -> Controls.
  final displayScreenId =
      screenIdForSection(_sectionOrder.indexOf('Display'));
  final controlsScreenId =
      screenIdForSection(_sectionOrder.indexOf('Controls'));

  for (var s = 0; s < _sectionOrder.length; s++) {
    final section = _sectionOrder[s];
    final screenId = screenIdForSection(s);
    screens.add(
      CanvasScreen(
        id: screenId,
        name: section,
        x: s * 420.0,
        y: 0.0,
        bg: 'surface',
        // Per-screen device demo: the Display screen previews as tablet,
        // everything else keeps the phone default (null).
        device: section == 'Display' ? 'tablet' : null,
      ),
    );
    var row = 0;
    for (final kind in _sectionKinds[section]!) {
      // The row kind takes the drop path's row branch (a container node
      // with no items, like CanvasStore.addRow creates).
      if (kind == 'row') {
        nodes.add(
          CanvasNode(
            id: _nextId(),
            screenId: screenId,
            x: 0.0,
            y: row * 48.0,
            items: const [],
            isRow: true,
          ),
        );
        row++;
        continue;
      }
      NodeAction? action;
      if (screenId == controlsScreenId && kind == 'button') {
        action = NodeAction(to: displayScreenId, transition: 'slide');
      } else if (screenId == displayScreenId &&
          kind == _sectionKinds['Display']!.first) {
        action = NodeAction(to: controlsScreenId, transition: 'fade');
      }
      nodes.add(
        CanvasNode(
          id: _nextId(),
          screenId: screenId,
          x: 0.0,
          y: row * 48.0,
          items: [
            CanvasItem(
              id: _nextId(),
              kind: kind,
              props: _dropProps(kind),
              action: action,
            ),
          ],
        ),
      );
      row++;
    }
  }

  // Tier demo screen: hiddenOn variants plus one breakpointValues node.
  screens.add(
    const CanvasScreen(
      id: tierScreenId,
      name: 'Tier demo',
      x: 8 * 420.0,
      y: 0.0,
      bg: 'surface',
    ),
  );
  Map<String, dynamic> labeled(String kind, String key, String value) {
    final props = _dropProps(kind);
    props[key] = value;
    return props;
  }

  nodes.addAll([
    CanvasNode(
      id: _nextId(),
      screenId: tierScreenId,
      x: 0.0,
      y: 0.0,
      hiddenOn: const {'mobile'},
      items: [
        CanvasItem(
          id: _nextId(),
          kind: 'button',
          props: labeled('button', 'label', 'Hidden on mobile'),
        ),
      ],
    ),
    CanvasNode(
      id: _nextId(),
      screenId: tierScreenId,
      x: 0.0,
      y: 48.0,
      hiddenOn: const {'tablet'},
      items: [
        CanvasItem(
          id: _nextId(),
          kind: 'card',
          props: labeled('card', 'title', 'Hidden on tablet'),
        ),
      ],
    ),
    CanvasNode(
      id: _nextId(),
      screenId: tierScreenId,
      x: 0.0,
      y: 96.0,
      hiddenOn: const {'desktop'},
      items: [
        CanvasItem(
          id: _nextId(),
          kind: 'badge',
          props: labeled('badge', 'label', 'Hidden on desktop'),
        ),
      ],
    ),
    CanvasNode(
      id: _nextId(),
      screenId: tierScreenId,
      x: 0.0,
      y: 144.0,
      items: [
        CanvasItem(
          id: _nextId(),
          kind: 'input',
          props: labeled('input', 'placeholder', 'Always visible'),
        ),
      ],
    ),
    CanvasNode(
      id: _nextId(),
      screenId: tierScreenId,
      x: 0.0,
      y: 192.0,
      breakpointValues: const {
        'tablet': {'label': 'Tablet CTA'},
        'desktop': {'label': 'Desktop CTA'},
      },
      items: [
        CanvasItem(
          id: _nextId(),
          kind: 'button',
          props: labeled('button', 'label', 'Responsive CTA'),
        ),
      ],
    ),
  ]);

  return ScreenDoc(
    screens: screens,
    nodes: nodes,
    // Clean-slate dark, no chrome override (mirrors CanvasStore.emptyDoc).
    theme: const CanvasTheme(
      paletteKey: 'clean-slate',
      dark: true,
      shape: 'rounded',
      motion: 'standard',
    ),
    meta: const DocMeta(
      title: 'Full palette demo',
      brief: 'Every palette section plus a responsive tier demo.',
    ),
  );
}

int _itemCount(ScreenDoc doc) =>
    doc.nodes.fold(0, (sum, node) => sum + node.items.length);

int _actionCount(ScreenDoc doc) => doc.nodes.fold(
      0,
      (sum, node) =>
          sum + node.items.where((item) => item.action != null).length,
    );

Never _fail(String message) {
  stderr.writeln('seed_full_palette: $message');
  exit(1);
}

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'usage: dart run tool/seed_full_palette.dart <out.json>',
    );
    exit(2);
  }

  final doc = buildFullPaletteDoc();

  final refs = doc.validateRefs();
  if (refs.isNotEmpty) {
    _fail('dangling refs:\n${refs.join('\n')}');
  }

  final out = File(args[0]);
  out.parent.createSync(recursive: true);
  out.writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(doc.toJson())}\n',
  );

  // Round-trip: read back through the model and assert equal counts, so
  // item props are proven fromJson-clean.
  late ScreenDoc back;
  try {
    back = ScreenDoc.fromJson(
      jsonDecode(out.readAsStringSync()) as Map<String, dynamic>,
    );
  } on FormatException catch (e) {
    _fail('round-trip parse failed: $e');
  }
  if (back.screens.length != doc.screens.length) {
    _fail(
      'round-trip screens mismatch: '
      '${back.screens.length} != ${doc.screens.length}',
    );
  }
  if (back.nodes.length != doc.nodes.length) {
    _fail(
      'round-trip nodes mismatch: '
      '${back.nodes.length} != ${doc.nodes.length}',
    );
  }
  if (_itemCount(back) != _itemCount(doc)) {
    _fail(
      'round-trip items mismatch: '
      '${_itemCount(back)} != ${_itemCount(doc)}',
    );
  }
  if (_actionCount(back) != _actionCount(doc)) {
    _fail(
      'round-trip actions mismatch: '
      '${_actionCount(back)} != ${_actionCount(doc)}',
    );
  }
  if (back.validateRefs().isNotEmpty) {
    _fail('round-trip refs mismatch: ${back.validateRefs().join(', ')}');
  }

  // Global id uniqueness across screens, nodes, and items.
  final seen = <String>{};
  final duplicates = <String>[];
  void take(String id) {
    if (!seen.add(id)) duplicates.add(id);
  }

  for (final screen in back.screens) {
    take(screen.id);
  }
  for (final node in back.nodes) {
    take(node.id);
    for (final item in node.items) {
      take(item.id);
    }
  }
  if (duplicates.isNotEmpty) {
    _fail('duplicate ids: ${duplicates.join(', ')}');
  }

  // Every catalog kind is showcased at least once.
  final kinds = {
    for (final node in back.nodes)
      for (final item in node.items) item.kind,
  };
  final missing = [
    for (final kind in _catalogDefaults.keys)
      if (!kinds.contains(kind)) kind,
  ];
  if (missing.isNotEmpty) {
    _fail('catalog kinds missing from doc: ${missing.join(', ')}');
  }

  // Tier demo + nav wiring shape.
  final tierNodes = [
    for (final node in back.nodes)
      if (node.screenId == 's9') node,
  ];
  if (tierNodes.length != 5) {
    _fail('expected 5 Tier demo nodes, found ${tierNodes.length}');
  }
  final hiddenVariants = tierNodes
      .where((node) => node.breakpointValues.isEmpty)
      .map((node) => node.hiddenOn.join('+'))
      .toSet();
  if (!hiddenVariants.containsAll({'mobile', 'tablet', 'desktop', ''})) {
    _fail(
      'Tier demo hiddenOn variants incomplete: ${hiddenVariants.join(', ')}',
    );
  }
  if (!tierNodes.any((node) => node.breakpointValues.isNotEmpty)) {
    _fail('Tier demo has no breakpointValues node');
  }
  if (_actionCount(back) != 2) {
    _fail('expected 2 tap actions, found ${_actionCount(back)}');
  }

  stdout.writeln(
    'seeded ${back.screens.length} screens, '
    '${back.nodes.length} nodes '
    '(${_itemCount(back)} items), '
    '${_actionCount(back)} actions -> ${args[0]} '
    '(refs clean, round-trip ok)',
  );
}
