// Reads components.json canvas blocks for canvas-ready kinds, resolves each
// kind's files[] + shared[] closure (reuse the file/destination lists verbatim),
// and emits a const map: destination -> file content.
import 'dart:convert';
import 'dart:io';

void main() {
  final root = File(Platform.script.toFilePath()).parent.parent.parent;
  final manifest = jsonDecode(File(
    '${root.path}/shadcn_flutter_kit/flutter_shadcn_kit/lib/registry/manifests/components.json',
  ).readAsStringSync()) as Map<String, dynamic>;
  final kitLib = '${root.path}/shadcn_flutter_kit/flutter_shadcn_kit/lib';
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_sources.dart — DO NOT EDIT.')
    ..writeln('const Map<String, String> kEmbeddedSources = {');
  for (final c in manifest['components'] as List) {
    if ((c as Map)['canvas'] == null) continue;
    for (final f in (c['files'] as List)) {
      final src = (f as Map)['source'] as String;
      final content = File('$kitLib/$src').readAsStringSync();
      // jsonEncode yields a double-quoted literal, but Dart would still
      // interpolate `$` from embedded sources — escape it (JSON escapes never
      // emit `$`, so every `$` here is a literal content char).
      final encoded = jsonEncode(content).replaceAll(r'$', r'\$');
      out.writeln("  ${jsonEncode(f['destination'])}: $encoded,");
    }
  }
  out.writeln('};');
  File('${root.path}/canvas_app/lib/canvas/_impl/embedded_sources.dart')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('embedded ${out.length} chars');
}
