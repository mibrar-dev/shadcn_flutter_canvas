/// Track R2 export/share loop tests.
///
/// The download/copy/file-pick sinks are injected — no platform channels,
/// no browser calls. Payload assertions pin the exact bytes each handler
/// passes to its sink; template checks pin ref-integrity + JSON round-trip.
library;

import 'dart:convert';

import 'package:canvas_app/canvas/canvas_store.dart';
import 'package:canvas_app/shadcn_ui.dart' as shadcn;
import 'package:canvas_app/ui/canvas_toolbar.dart';
import 'package:canvas_app/ui/editor_buttons.dart';
import 'package:canvas_app/ui/editor_tokens.dart';
import 'package:canvas_app/ui/export_panel.dart';
import 'package:canvas_app/ui/open_dialog.dart';
import 'package:canvas_core/canvas_core.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';

/// Pumps [child] under the editor theme + material scaffolding the dialogs
/// and toolbar need (`EditorTheme.of`, `Navigator`, kit tooltips).
Future<void> pumpChrome(WidgetTester tester, Widget child) async {
  await tester.pumpWidget(
    MaterialApp(
      home: Scaffold(
        body: EditorTheme(colors: EditorColors.light, child: child),
      ),
    ),
  );
  await tester.pumpAndSettle();
}

void main() {
  group('filenames', () {
    test('exportSlug lowercases and dashes titles', () {
      expect(exportSlug('Login flow'), 'login-flow');
      expect(exportSlug('  Showcase!! v2 '), 'showcase-v2');
      expect(exportSlug(''), 'design');
      expect(exportSlug('---'), 'design');
    });

    test('exportFileName joins slug, date, and extension', () {
      expect(
        exportFileName(
          title: 'Login flow',
          extension: 'zip',
          date: DateTime(2026, 9, 6),
        ),
        'login-flow-20260906.zip',
      );
    });
  });

  group('export dialog', () {
    testWidgets('all options render', (tester) async {
      await pumpChrome(
        tester,
        ExportDialog(store: CanvasStore(initial: buildBlankTemplate())),
      );
      for (final label in [
        'Download project ZIP',
        'Download single .dart file',
        'Copy single-file code',
        'Copy share link',
        'Copy AI prompt',
        'Save doc JSON to file',
        'Close',
      ]) {
        expect(find.text(label), findsOneWidget, reason: label);
      }
    });

    testWidgets('ZIP download passes zipBytes with a dated filename',
        (tester) async {
      final downloads = <({List<int> bytes, String name, String mime})>[];
      await pumpChrome(
        tester,
        ExportDialog(
          store: CanvasStore(initial: buildBlankTemplate()),
          isWebOverride: true,
          onDownload: (bytes, name, mime) async {
            downloads.add((bytes: bytes, name: name, mime: mime));
          },
        ),
      );
      await tester.tap(find.text('Download project ZIP'));
      await tester.pumpAndSettle();

      expect(downloads, hasLength(1));
      final zip = downloads.single;
      // ZIP local-file-header magic.
      expect(zip.bytes.sublist(0, 4), orderedEquals([0x50, 0x4B, 0x03, 0x04]));
      expect(zip.mime, kZipMimeType);
      expect(
        zip.name,
        matches(RegExp(r'^blank-\d{8}\.zip$')),
      );
      expect(find.textContaining('Download started:'), findsOneWidget);
    });

    testWidgets('single-file download and copy share the built code',
        (tester) async {
      final downloads = <({List<int> bytes, String name, String mime})>[];
      final copies = <String>[];
      final store = CanvasStore(initial: buildBlankTemplate());
      final expected = buildExportSingleFile(store.doc);
      expect(expected, startsWith('// generated by shadcn canvas'));

      await pumpChrome(
        tester,
        ExportDialog(
          store: store,
          isWebOverride: true,
          onDownload: (bytes, name, mime) async {
            downloads.add((bytes: bytes, name: name, mime: mime));
          },
          onCopy: (text) async {
            copies.add(text);
          },
        ),
      );

      await tester.tap(find.text('Download single .dart file'));
      await tester.pumpAndSettle();
      expect(downloads, hasLength(1));
      expect(utf8.decode(downloads.single.bytes), expected);
      expect(downloads.single.name, matches(RegExp(r'^blank-\d{8}\.dart$')));

      await tester.tap(find.text('Copy single-file code'));
      await tester.pumpAndSettle();
      expect(copies, [expected]);
      expect(find.text('Copied'), findsOneWidget);
    });

    testWidgets('share-link and prompt copies reuse the pure builders',
        (tester) async {
      final copies = <String>[];
      final store = CanvasStore(initial: buildBlankTemplate());
      await pumpChrome(
        tester,
        ExportDialog(
          store: store,
          isWebOverride: true,
          onCopy: (text) async {
            copies.add(text);
          },
        ),
      );

      await tester.tap(find.text('Copy share link'));
      await tester.pumpAndSettle();
      expect(copies, hasLength(1));
      expect(copies.single, startsWith(kShareFragmentPrefix));
      expect(copies.single, encode(store.doc));

      await tester.tap(find.text('Copy AI prompt'));
      await tester.pumpAndSettle();
      expect(copies, hasLength(2));
      expect(copies[1], buildPrompt(store.doc));
      expect(copies[1], isNotEmpty);
    });

    testWidgets('off-web downloads render the guard and call no sink',
        (tester) async {
      var calls = 0;
      await pumpChrome(
        tester,
        ExportDialog(
          store: CanvasStore(initial: buildBlankTemplate()),
          isWebOverride: false,
          onDownload: (bytes, name, mime) async {
            calls++;
          },
        ),
      );
      await tester.tap(find.text('Download project ZIP'));
      await tester.pump();
      expect(calls, 0);
      expect(find.text(kNonWebDownloadMessage), findsOneWidget);
    });
  });

  group('open dialog project files', () {
    testWidgets('save-to-file downloads the doc JSON', (tester) async {
      final downloads = <({List<int> bytes, String name, String mime})>[];
      final store = CanvasStore(initial: buildBlankTemplate());
      await pumpChrome(
        tester,
        OpenDialog(
          store: store,
          isWebOverride: true,
          onDownload: (bytes, name, mime) async {
            downloads.add((bytes: bytes, name: name, mime: mime));
          },
        ),
      );

      expect(find.text('Load from file…'), findsOneWidget);
      expect(find.text('Save to file'), findsOneWidget);
      for (final name in ['Blank', 'Login flow', 'Showcase']) {
        expect(find.text(name), findsOneWidget, reason: name);
      }

      await tester.tap(find.text('Save to file'));
      await tester.pumpAndSettle();
      expect(downloads, hasLength(1));
      final saved = downloads.single;
      expect(saved.name, matches(RegExp(r'^blank-\d{8}\.json$')));
      expect(saved.mime, kTextMimeType);
      // Saved text re-parses to the same doc.
      final back = ScreenDoc.fromJson(
        jsonDecode(utf8.decode(saved.bytes)) as Map<String, dynamic>,
      );
      expect(back.validateRefs(), isEmpty);
      expect(back.screens.length, store.doc.screens.length);
      expect(back.nodes.length, store.doc.nodes.length);
      expect(find.textContaining('Saved blank-'), findsOneWidget);
    });

    testWidgets('load-from-file imports through the paste path',
        (tester) async {
      final store = CanvasStore();
      final payload = docJsonText(buildLoginTemplate());
      await pumpChrome(
        tester,
        OpenDialog(
          store: store,
          isWebOverride: true,
          onPickFile: () async => payload,
        ),
      );
      await tester.tap(find.text('Load from file…'));
      await tester.pumpAndSettle();
      // Imported and closed.
      expect(find.byType(shadcn.AlertDialog), findsNothing);
      expect(store.doc.meta.title, 'Login flow');
      expect(store.canUndo, isTrue);
    });

    testWidgets('cancelled picker stays open and silent', (tester) async {
      final store = CanvasStore();
      await pumpChrome(
        tester,
        OpenDialog(
          store: store,
          isWebOverride: true,
          onPickFile: () async => null,
        ),
      );
      await tester.tap(find.text('Load from file…'));
      await tester.pumpAndSettle();
      expect(find.byType(shadcn.AlertDialog), findsOneWidget);
      expect(store.doc.meta.title, 'Untitled');
    });

    testWidgets('off-web file buttons render the guard', (tester) async {
      await pumpChrome(
        tester,
        OpenDialog(
          store: CanvasStore(),
          isWebOverride: false,
        ),
      );
      await tester.tap(find.text('Save to file'));
      await tester.pump();
      expect(find.text(kNonWebDownloadMessage), findsOneWidget);
      await tester.tap(find.text('Load from file…'));
      await tester.pump();
      expect(find.text(kNonWebDownloadMessage), findsOneWidget);
    });
  });

  group('templates', () {
    for (final entry in templateBuilders.entries) {
      test('${entry.key} validates and round-trips', () {
        final doc = entry.value();
        expect(doc.validateRefs(), isEmpty);
        final back = ScreenDoc.fromJson(
          jsonDecode(jsonEncode(doc.toJson())) as Map<String, dynamic>,
        );
        expect(back.validateRefs(), isEmpty);
        expect(back.screens.length, doc.screens.length);
        expect(back.nodes.length, doc.nodes.length);
        expect(
          back.nodes.fold(0, (sum, n) => sum + n.items.length),
          doc.nodes.fold(0, (sum, n) => sum + n.items.length),
        );
        // Global id uniqueness across screens, nodes, and items.
        final seen = <String>{};
        for (final s in back.screens) {
          expect(seen.add(s.id), isTrue, reason: 'dup ${s.id}');
        }
        for (final n in back.nodes) {
          expect(seen.add(n.id), isTrue, reason: 'dup ${n.id}');
          for (final i in n.items) {
            expect(seen.add(i.id), isTrue, reason: 'dup ${i.id}');
          }
        }
      });
    }

    test('login template wires the sign-in cycle', () {
      final doc = buildLoginTemplate();
      bool hasAction(String from, String to) => doc.nodes.any(
            (n) =>
                n.screenId == from &&
                n.items.any((i) => i.action?.to == to),
          );
      expect(hasAction('s1', 's2'), isTrue);
      expect(hasAction('s2', 's1'), isTrue);
    });

    test('showcase template wires the two-screen chain', () {
      final doc = buildShowcaseTemplate();
      bool hasAction(String from, String to) => doc.nodes.any(
            (n) =>
                n.screenId == from &&
                n.items.any((i) => i.action?.to == to),
          );
      expect(hasAction('s1', 's2'), isTrue);
      expect(hasAction('s2', 's1'), isTrue);
    });

    testWidgets('denied confirm keeps the doc and the dialog', (tester) async {
      var confirmName;
      final store = CanvasStore();
      await pumpChrome(
        tester,
        OpenDialog(
          store: store,
          onConfirmReplace: (context, name) async {
            confirmName = name;
            return false;
          },
        ),
      );
      await tester.tap(find.text('Login flow'));
      await tester.pumpAndSettle();
      expect(confirmName, 'Login flow');
      expect(store.doc.meta.title, 'Untitled');
      expect(store.canUndo, isFalse);
      expect(find.byType(shadcn.AlertDialog), findsOneWidget);
    });

    testWidgets('confirmed replace swaps the doc (undoable) and closes',
        (tester) async {
      final store = CanvasStore();
      await pumpChrome(
        tester,
        OpenDialog(
          store: store,
          onConfirmReplace: (context, name) async => true,
        ),
      );
      await tester.tap(find.text('Showcase'));
      await tester.pumpAndSettle();
      expect(find.byType(shadcn.AlertDialog), findsNothing);
      expect(store.doc.meta.title, 'Showcase');
      expect(store.doc.validateRefs(), isEmpty);
      expect(store.canUndo, isTrue);
      expect(store.undo(), isTrue);
      expect(store.doc.meta.title, 'Untitled');
    });
  });

  group('toolbar export control', () {
    Future<void> pumpToolbar(
      WidgetTester tester, {
      VoidCallback? onExport,
    }) {
      return tester.pumpWidget(
        MaterialApp(
          home: Scaffold(
            body: EditorTheme(
              colors: EditorColors.light,
              child: CanvasToolbar(
                panMode: false,
                onPanModeChanged: (_) {},
                onAddScreen: () {},
                onPreview: () {},
                onUndo: null,
                onRedo: null,
                onDelete: () {},
                hasSelection: false,
                onOpen: () {},
                onExport: onExport,
              ),
            ),
          ),
        ),
      );
    }

    Finder exportButton() => find.byWidgetPredicate(
          (w) => w is EditorIconButton && w.icon == Icons.ios_share,
        );

    testWidgets('export button calls through', (tester) async {
      var calls = 0;
      await pumpToolbar(tester, onExport: () => calls++);
      await tester.tap(exportButton());
      await tester.pump();
      expect(calls, 1);
    });

    testWidgets('null export renders disabled', (tester) async {
      await pumpToolbar(tester);
      expect(tester.widget<EditorIconButton>(exportButton()).onPressed, isNull);
    });
  });
}
