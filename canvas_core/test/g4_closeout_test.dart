/// Track G4 — demote + closeout.
///
/// * `demote`: the single-file linker is KEPT (entry point works) but
///   demoted behind [ExportMode] — the bundle is the supported path, the
///   inline-sources path carries the experimental label.
/// * `barrel`: `src/emit/emit.dart` resolves as one import (the §8.2
///   surface), re-exported from `canvas_core.dart`.
/// * Gates evidence in-suite: byte-exact goldens live in `g3_gap_test`;
///   here gate 3 (generated fixtures reformat to themselves) and gate 7
///   (placeholder scan over a kitchen-sink bundle screen) are pinned
///   directly. Gates 4–5 status is recorded in `docs/BUILD_G4_CLOSEOUT.md`.
library;

import 'dart:io';

import 'package:canvas_core/canvas_core.dart';
import 'package:dart_style/dart_style.dart';
import 'package:test/test.dart';

/// All ten G3 kinds plus a primitive and a kit kind: every supported
/// exporter path must render them all with zero placeholders.
ScreenDoc _kitchenSinkDoc() {
  const kinds = [
    'chip',
    'alert',
    'circular_progress_indicator',
    'linear_progress_indicator',
    'triple_dots',
    'dot_indicator',
    'empty_state',
    'code_snippet',
    'number_ticker',
    'text_area',
    'container',
    'button',
  ];
  return ScreenDoc.fromJson({
    'screens': [
      {'id': 's1', 'name': 'Home', 'x': 0.0, 'y': 0.0, 'bg': 'surface'},
    ],
    'nodes': [
      for (var i = 0; i < kinds.length; i++)
        {
          'id': 'n$i',
          'screenId': 's1',
          'x': 0.0,
          'y': i * 48.0,
          'items': [
            {'id': 'i$i', 'kind': kinds[i]},
          ],
        },
    ],
    'theme': {
      'paletteKey': 'slate',
      'dark': false,
      'shape': 'rounded',
      'motion': 'standard',
    },
    'meta': {'title': 'G4', 'brief': ''},
  });
}

void main() {
  group('g4 demote (single-file kept, experimental)', () {
    test('ExportMode declares both paths, bundle first', () {
      expect(ExportMode.values, [
        ExportMode.bundle,
        ExportMode.inlineSourcesExperimental,
      ]);
    });

    test('experimental qualifier is part of the label contract', () {
      expect(exportModeLabel(ExportMode.bundle), 'Project');
      expect(
        exportModeLabel(ExportMode.inlineSourcesExperimental),
        contains('experimental'),
      );
    });

    test('linker entry point still works (demoted, not deleted)', () {
      final out = buildSingleFile(_kitchenSinkDoc(), const {});
      expect(out, startsWith('// generated by shadcn canvas'));
      expect(out, isNotEmpty);
    });
  });

  group('g4 barrel (src/emit as one import)', () {
    test('registry surface resolves through the barrel', () {
      // Every symbol below is reached via `canvas_core.dart` (which
      // re-exports `src/emit/emit.dart`, the §8.2 surface) — a single
      // import covers the whole registry surface, so no ambiguity.
      expect(g3Registry().driftKinds, isEmpty);
      expect(primitiveRegistry().emitterCount, 10);
      expect(kG3KitImport, contains('flutter_shadcn_kit'));
      expect(needsModel(['text_area']), isTrue);
      expect(needsModel(['chip']), isFalse);
    });
  });

  group('g4 gates evidence', () {
    test('gate 3: generated fixtures reformat to themselves', () {
      const fixtures = [
        'g3_chip',
        'g3_alert',
        'g3_circular_progress_indicator',
        'g3_linear_progress_indicator',
        'g3_triple_dots',
        'g3_dot_indicator',
        'g3_empty_state',
        'g3_code_snippet',
        'g3_number_ticker',
        'g3_text_area',
        'g3_text_area_model',
      ];
      for (final name in fixtures) {
        final content =
            File('test/fixtures/$name.expected.dart').readAsStringSync();
        expect(
          DartFormatter().format(content),
          content,
          reason: '$name is not a formatter fixpoint',
        );
      }
    });

    test('gate 7: placeholder scan over the kitchen-sink screen', () {
      final bundle = buildCleanBundle(_kitchenSinkDoc(), const {});
      final path = bundle.files.keys.singleWhere(
        (k) => k.startsWith('lib/ui/screens/'),
      );
      final screen = bundle.files[path]!;
      expect(screen, isNot(contains('(not yet bridged)')));
      for (final ctor in [
        'Chip(',
        'Alert(',
        'CircularProgressIndicator(',
        'LinearProgressIndicator(',
        'MoreDots(',
        'DotIndicator(',
        'EmptyState(',
        'CodeSnippet(',
        'NumberTicker(',
        'TextArea(',
        'Container(',
        'PrimaryButton(',
      ]) {
        expect(screen, contains(ctor), reason: ctor);
      }
    });
  });
}
