        // member); previously codegen fell through to `PrimaryButton`.
        'text' => 'TextButton',
        _ => 'PrimaryButton',
      };
      final size = switch (props['size']) {
        'sm' => 'ButtonSize.small',
        'lg' => 'ButtonSize.large',
        _ => 'ButtonSize.normal',
