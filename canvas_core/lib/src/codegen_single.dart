  switch (item.kind) {
    case 'button':
      final constructor = switch (props['variant']) {
        'secondary' => 'SecondaryButton',
        'outline' => 'OutlineButton',
        'ghost' => 'GhostButton',
        'destructive' => 'DestructiveButton',
        'link' => 'LinkButton',
